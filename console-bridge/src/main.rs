type I2c0Bus = Mutex<NoopRawMutex, RefCell<i2c::I2c<'static, I2C0, i2c::Blocking>>>;
type I2c0Mcp = MCP23017<I2cDevice<'static, NoopRawMutex, i2c::I2c<'static, I2C0, i2c::Blocking>>>;

bind_interrupts!(struct Irqs {
    USBCTRL_IRQ => usb::InterruptHandler<USB>;
    UART0_IRQ => uart::InterruptHandler<UART0>;
});

const B: [u32; 4] = [0x55555555, 0x33333333, 0x0F0F0F0F, 0x00FF00FF];
const S: [u32; 4] = [1, 2, 4, 8];
const NIBBLE_REVERSE_LOOKUP: [u8; 16] = [
    0x0, 0x8, 0x4, 0xc, 0x2, 0xa, 0x6, 0xe, 0x1, 0x9, 0x5, 0xd, 0x3, 0xb, 0x7, 0xf,
];

static STOP_STATE: Signal<CriticalSectionRawMutex, u64> = Signal::new();
static PRESET_STORE: StaticCell<PresetStore> = StaticCell::new();

// Queue for all events on the organ. These events can be either generated by mechanical interactions with the console
// (e.g. pressing a stop tab button, moving an expression pedal, etc.) or received over USB.
static MAIN_EVENT_BUS: Channel<CriticalSectionRawMutex, EventIn, 128> = Channel::new();

// This channel has a relatively large buffer to accommodate bursts of MIDI messages when recalling presets. If the USB
// host is slow or disconnected (e.g. in analog-only mode), we don't want to block the entire system.
static OUTBOUND_USB_MIDI_EVENT_BUS: Channel<CriticalSectionRawMutex, LiveEvent, 128> =
    Channel::new();

static USB_CONFIG_DESCRIPTOR: ConstStaticCell<[u8; 256]> = ConstStaticCell::new([0; 256]);
static USB_BOS_DESCRIPTOR: ConstStaticCell<[u8; 256]> = ConstStaticCell::new([0; 256]);
static USB_CONTROL_BUF: ConstStaticCell<[u8; 64]> = ConstStaticCell::new([0; 64]);

fn reverse_byte(a: &u8) -> u8 {
    let mut b = *a;
    b = (b & 0xF0) >> 4 | (b & 0x0F) << 4;
    b = (b & 0xCC) >> 2 | (b & 0x33) << 2;
    b = (b & 0xAA) >> 1 | (b & 0x55) << 1;
    b
}

fn interleave_bits(a: u16, b: u16) -> u32 {
    let mut x = a as u32;
    let mut y = b as u32;

    for i in (0..4).rev() {
        x = (x | (x << S[i])) & B[i];
        y = (y | (y << S[i])) & B[i];
    }
    x | (y << 1)
}

fn stop_tab_midi_cc_message(div: usize, i: u8, div_stop_state: u16) -> LiveEvent<'static> {
    let mut midi_val: u7 = 0.into();
    if div_stop_state >> i & 1 == 1 {
        midi_val = u7::max_value();
    }
    LiveEvent::Midi {
        channel: u4::from(div as u8),
        message: MidiMessage::Controller {
            controller: (117 - i).into(),
            value: midi_val,
        },
    }
}

fn get_mcps(i2c_bus: &'static I2c0Bus) -> [[I2c0Mcp; 2]; 4] {
    [[0x20, 0x21], [0x22, 0x23], [0x24, 0x25], [0x26, 0x27]].map(|[addr0, addr1]| {
        [
            MCP23017::new(I2cDevice::new(i2c_bus), addr0),
            MCP23017::new(I2cDevice::new(i2c_bus), addr1),
        ]
    })
}

