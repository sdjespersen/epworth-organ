type I2c0Bus = Mutex<NoopRawMutex, RefCell<i2c::I2c<'static, I2C0, i2c::Blocking>>>;
type I2c0Mcp = MCP23017<I2cDevice<'static, NoopRawMutex, i2c::I2c<'static, I2C0, i2c::Blocking>>>;

bind_interrupts!(struct Irqs {
    ADC_IRQ_FIFO => adc::InterruptHandler;
    USBCTRL_IRQ => rp_usb::InterruptHandler<USB>;
    UART0_IRQ => uart::BufferedInterruptHandler<UART0>;
});

const MCP_I2C_ADDRESSES: [[u8; 2]; 4] = [[0x20, 0x21], [0x22, 0x23], [0x24, 0x25], [0x26, 0x27]];
const DIVISIONS: [Division; 4] = [
    Division::Swell,
    Division::Great,
    Division::Choir,
    Division::Pedal,
];

// This stop state representation is LSB first, i.e. looking at the stop tab panels from the front, LSB is on the left.
// Furthermore, the 16 bits corresponding to the swell division are in the 16 lowest bits, the next 16 are the great,
// followed by the choir division and finally the pedal division. The MSB for each division is always 0, as it is not
// connected to any physical hardware. (No division has more than 15 stops.)
static STOP_STATE: Signal<CriticalSectionRawMutex, u64> = Signal::new();
static PRESET_STORE: StaticCell<Presets> = StaticCell::new();

// Queue for all commands on the organ. These commands can be either generated by mechanical interactions with the
// console (e.g. pressing a stop tab button, moving an expression pedal, etc.), including mechanical interactions
// relayed to this particular MCU over UART, or they can be received over USB MIDI.
static COMMANDS: Channel<CriticalSectionRawMutex, (Command, CommandSource), 8> = Channel::new();

// Queues for events destined for the decoders (via UART) or the computer (via USB).
static UART_EVENTS: Channel<CriticalSectionRawMutex, Event, 8> = Channel::new();
static USB_EVENTS: Channel<CriticalSectionRawMutex, Event, 8> = Channel::new();

static USB_CONFIG_DESCRIPTOR: ConstStaticCell<[u8; 512]> = ConstStaticCell::new([0; 512]);
static USB_BOS_DESCRIPTOR: ConstStaticCell<[u8; 256]> = ConstStaticCell::new([0; 256]);
static USB_CONTROL_BUF: ConstStaticCell<[u8; 128]> = ConstStaticCell::new([0; 128]);

fn get_mcps(i2c_bus: &'static I2c0Bus) -> [[I2c0Mcp; 2]; 4] {
    MCP_I2C_ADDRESSES.map(|[addr0, addr1]| {
        [
            MCP23017::new(I2cDevice::new(i2c_bus), addr0),
            MCP23017::new(I2cDevice::new(i2c_bus), addr1),
        ]
    })
}

#[embassy_executor::task]
async fn write_stop_state_to_leds(i2c_bus: &'static I2c0Bus) {
    let mcp_pairs = &mut get_mcps(i2c_bus);

    loop {
        let mut stop_state: u64 = STOP_STATE.wait().await;

        // This is our approach to batching lots of little changes: Wait for a brief interval before reading the stop
        // states again.
        Timer::after_millis(1).await;

        stop_state = STOP_STATE.try_take().unwrap_or(stop_state);

        for (mcp_pair, div) in mcp_pairs.iter_mut().zip(DIVISIONS) {
            // Remember, stop state is LSB first.
            let state = stop_state >> (16 * div as u8) & 0xFFFF;
            let left_half = !(state & 0xFF) as u8;
            let right_half = !(state >> 8) as u8;
            mcp_pair[0]
                .write_gpio(Port::GPIOA, (left_half & 0x7F) << 1)
                .unwrap();
            mcp_pair[0]
                .write_gpio(Port::GPIOB, left_half & 0x80)
                .unwrap();
            mcp_pair[1]
                .write_gpio(Port::GPIOA, right_half & 0x7F)
                .unwrap();
        }
    }
}

#[embassy_executor::task]
async fn scan_stop_tab_buttons(i2c_bus: &'static I2c0Bus) {
    let mut mcp_pairs = get_mcps(i2c_bus);
    let mut stop_tab_button_debouncers: [Debouncer<5>; 4] = [
        Debouncer::<5>::new(0xFFFF),
        Debouncer::<5>::new(0xFFFF),
        Debouncer::<5>::new(0xFFFF),
        Debouncer::<5>::new(0xFFFF),
    ];

    loop {
        for (mcp_pair, div) in mcp_pairs.iter_mut().zip(DIVISIONS) {
            // These readings are L-to-R looking at the front of the stop tab panels, aka MSB first.
            let mut raw_reading = 0x01u16; // LSB always 1, not hooked up
            raw_reading |= ((mcp_pair[0].read_gpio(Port::GPIOA).unwrap() & 0x01) as u16) << 8;
            raw_reading |= ((mcp_pair[0].read_gpio(Port::GPIOB).unwrap() & 0x7F) as u16) << 9;
            raw_reading |= ((mcp_pair[1].read_gpio(Port::GPIOB).unwrap() & 0x7F) as u16) << 1;
            stop_tab_button_debouncers[div as usize].update(raw_reading);

            for i in stop_tab_button_debouncers[div as usize].falling_edges() {
                // Because the raw readings (and hence debouncers) are MSB first, need to invert the stop number.
                if let Some(stop) = Stop::try_from(div, 15 - i) {
                    COMMANDS
                        .send((Command::StopToggle(stop), CommandSource::Local))
                        .await;
                }
            }
        }
        Timer::after_micros(500).await;
    }
}

#[embassy_executor::task]
async fn scan_pistons(
    load_pin: Peri<'static, AnyPin>,
    clock_pin: Peri<'static, AnyPin>,
    data_pin: Peri<'static, AnyPin>,
) {
    let mut piston_debouncer = Debouncer::<5>::new(0xFFFF);

    // Load piston states into 74HC165 shift register
    let mut piston_load_pin = Output::new(load_pin, Level::Low);
    let mut piston_clock_pin = Output::new(clock_pin, Level::Low);
    let piston_data_pin = Input::new(data_pin, Pull::Up);

    loop {
        piston_load_pin.set_low();
        piston_load_pin.set_high();

        let mut raw_piston_reading = 0u16;
        // Ensure clock pin low first...
        piston_clock_pin.set_low();

        // ...then clock the data into the piston readings.
        for i in 0..8 {
            if piston_data_pin.is_high() {
                raw_piston_reading |= 1 << i;
            }
            piston_clock_pin.set_high();
            piston_clock_pin.set_low();
        }
        // Nothing is hooked up to 8-15 right now...
        raw_piston_reading |= 0xFF00;

        piston_debouncer.update(raw_piston_reading);

        for i in piston_debouncer.falling_edges() {
            if i == 0 {
                COMMANDS
                    .send((Command::EnableSave(true), CommandSource::Local))
                    .await;
            } else if i == 1 {
                COMMANDS
                    .send((Command::GeneralCancel(), CommandSource::Local))
                    .await;
            } else {
                COMMANDS
                    .send((Command::RecallPreset(i), CommandSource::Local))
                    .await;
            }
        }

        for i in piston_debouncer.rising_edges() {
            if i == 0 {
                COMMANDS
                    .send((Command::EnableSave(false), CommandSource::Local))
                    .await;
            }
        }

        Timer::after_micros(500).await;
    }
}

#[embassy_executor::task]
async fn read_crescendo_position(
    mut cresc_adc: adc::Adc<'static, adc::Async>,
    mut cresc_channel: adc::Channel<'static>,
) {
    let mut cresc_pos = 0u8;
    let mut level = 0u16;

    loop {
        // Pico 2 ADC has 12 bits of resolution, but it's pretty noisy. We do a few things here to help with that:
        // - Smooth out the readings with exponential decay (weighted average with current reading).
        // - Drop the 5 least significant bits (yes, quite a few!). The resulting reading is MIDI-compatible (7 bits).
        let raw_level = cresc_adc.read(&mut cresc_channel).await.unwrap();
        level = (level * 7 + raw_level) / 8;
        let new_cresc_pos = ((level >> 5) & 0x7F) as u8;
        if new_cresc_pos != cresc_pos {
            cresc_pos = new_cresc_pos;
            COMMANDS
                .send((Command::Crescendo(cresc_pos), CommandSource::Local))
                .await;
        }
        Timer::after_millis(1).await;
    }
}

#[embassy_executor::task]
async fn usb_midi_writer(
    mut usb_midi_tx: eusb_midi::Sender<'static, rp_usb::Driver<'static, USB>>,
) {
    // TODO: Handle the case where the USB cable gets connected/disconnected while the program is running.
    // We can probably implement this by breaking out of the inner loop if we time out when writing packets.
    usb_midi_tx.wait_connection().await;

    loop {
        let event = USB_EVENTS.receive().await;
        write_event_to_usb(event, &mut usb_midi_tx).await;
    }
}

#[embassy_executor::task]
async fn usb_midi_reader(
    mut usb_midi_rx: eusb_midi::Receiver<'static, rp_usb::Driver<'static, USB>>,
) {
    // TODO: Handle the case where the USB cable gets connected/disconnected while the program is running.
    usb_midi_rx.wait_connection().await;

    let mut data = [0u8; 64];

    loop {
        receive_command_from_usb(&mut data, &mut usb_midi_rx, async |cmd| {
            COMMANDS.send((cmd, CommandSource::External)).await;
        })
        .await;
    }
}

#[embassy_executor::task]
async fn usb_midi(spawner: Spawner, usb: Peri<'static, USB>) {
    let driver = rp_usb::Driver::new(usb, Irqs);
    let mut config = UsbConfig::new(0xc0de, 0xcafe);
    config.manufacturer = Some("RP Pico 2");
    config.product = Some("Epworth Organ MIDI");
    config.serial_number = Some("12345678");
    config.max_power = 100;
    config.max_packet_size_0 = 64;

    let mut builder = UsbBuilder::new(
        driver,
        config,
        USB_CONFIG_DESCRIPTOR.take(),
        USB_BOS_DESCRIPTOR.take(),
        &mut [], // no msos descriptors
        USB_CONTROL_BUF.take(),
    );

    let midi_class = MidiClass::new(&mut builder, 1, 1, 64);

    // Build the builder.
    let mut usb_device = builder.build();

    let (usb_midi_tx, usb_midi_rx) = midi_class.split();

    spawner.spawn(usb_midi_writer(usb_midi_tx)).unwrap();
    spawner.spawn(usb_midi_reader(usb_midi_rx)).unwrap();

    // Run the USB device forever.
    loop {
        usb_device.run().await;
    }
}

#[embassy_executor::task]
async fn uart_reader(uart_rx: uart::BufferedUartRx) {
    let mut uart_rdr = UartReader::new(uart_rx);

    loop {
        uart_rdr
            .feed::<Command>(async |data| {
                COMMANDS.send((data, CommandSource::Local)).await;
            })
            .await;
    }
}

#[embassy_executor::task]
async fn uart_writer(mut uart_tx: uart::BufferedUartTx) {
    loop {
        let event = UART_EVENTS.receive().await;
        // We have to be careful here about buffer size! Preset recall serializes to 12 bytes in my testing. I'm
        // leaving a few extra just in case i introduce anything around that size.
        let mut buf = [0u8; 16];
        let written = to_slice_cobs(&event, &mut buf).unwrap();
        let _ = uart_tx.write_all(written).await;
    }
}

fn setup_mcps(i2c_bus: &'static I2c0Bus) {
    for mcp_pair in get_mcps(i2c_bus).iter_mut() {
        mcp_pair[0].init_hardware().unwrap();
        mcp_pair[1].init_hardware().unwrap();
        // Set pin modes (input/output) for MCP23017s based on the schematic
        mcp_pair[0].port_mode(Port::GPIOA, 0x01).unwrap();
        mcp_pair[0].port_mode(Port::GPIOB, 0x7F).unwrap();
        mcp_pair[1].port_mode(Port::GPIOA, 0x00).unwrap();
        mcp_pair[1].port_mode(Port::GPIOB, 0x7F).unwrap();
        // Write all outputs high, inputs low.
        mcp_pair[0].write_gpio(Port::GPIOA, 0xFE).unwrap();
        mcp_pair[0].write_gpio(Port::GPIOB, 0x80).unwrap();
        mcp_pair[1].write_gpio(Port::GPIOA, 0x7F).unwrap();
        mcp_pair[1].write_gpio(Port::GPIOB, 0x00).unwrap();
    }
}

#[embassy_executor::task]
async fn main_event_handler(preset_store: &'static mut Presets<'static>) {
    // let mut stop_state: u64 = 0u64;
    // let mut awaiting_save = false;
    let mut encoder = Encoder::new(preset_store);

    // Flush initial stop state.
    STOP_STATE.signal(encoder.get_stop_state());

    loop {
        let (command, src) = COMMANDS.receive().await;

        let command_result = encoder.handle(command).await;

        if command_result.1 {
            STOP_STATE.signal(encoder.get_stop_state())
        }

        if let Some(e) = command_result.0 {
            if let CommandSource::Local = src {
                let _ = USB_EVENTS.try_send(e);
            }
            UART_EVENTS.send(e).await;
        }
    }
}

#[embassy_executor::main]
async fn main(spawner: Spawner) {
    let p = embassy_rp::init(Default::default());

    let i2c = embassy_rp::i2c::I2c::new_blocking(p.I2C0, p.PIN_5, p.PIN_4, i2c::Config::default());
    static I2C_BUS: StaticCell<I2c0Bus> = StaticCell::new();
    let i2c_bus = I2C_BUS.init(Mutex::new(i2c.into()));

    spawner
        .spawn(main_event_handler(
            PRESET_STORE.init(Presets::new(Flash::new(p.FLASH, p.DMA_CH0))),
        ))
        .unwrap();

    static TX_BUF: StaticCell<[u8; 16]> = StaticCell::new();
    let tx_buf = &mut TX_BUF.init([0; 16])[..];
    static RX_BUF: StaticCell<[u8; 16]> = StaticCell::new();
    let rx_buf = &mut RX_BUF.init([0; 16])[..];
    let uart_txrx = uart::BufferedUart::new(
        p.UART0,
        p.PIN_16,
        p.PIN_17,
        Irqs,
        tx_buf,
        rx_buf,
        uart::Config::default(),
    );
    let (uart_tx, uart_rx) = uart_txrx.split();
    spawner.spawn(uart_reader(uart_rx)).unwrap();
    spawner.spawn(uart_writer(uart_tx)).unwrap();

    setup_mcps(i2c_bus);
    spawner.spawn(scan_stop_tab_buttons(i2c_bus)).unwrap();
    spawner.spawn(write_stop_state_to_leds(i2c_bus)).unwrap();
    spawner
        .spawn(scan_pistons(
            p.PIN_11.into(),
            p.PIN_12.into(),
            p.PIN_13.into(),
        ))
        .unwrap();
    spawner
        .spawn(read_crescendo_position(
            adc::Adc::new(p.ADC, Irqs, adc::Config::default()),
            adc::Channel::new_pin(p.PIN_26, Pull::None),
        ))
        .unwrap();
    spawner.spawn(usb_midi(spawner, p.USB)).unwrap();

    defmt::info!("All tasks spawned.");

    // Heartbeat task comes last, and happens on the main loop, roughly indicating that all tasks spawned successfully.
    let mut led = Output::new(p.PIN_25, Level::Low);

    loop {
        led.toggle();
        Timer::after_secs(1).await;
    }
}
